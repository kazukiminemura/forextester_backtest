"""Generate the TradingView replay overlay from the closed #46 candidate trades."""

import argparse
import json
from collections import defaultdict
from datetime import date
from decimal import Decimal
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXPERIMENT = ROOT / "docs/quant_organization/experiments/pf15_us_8k_price_drift_20261104"
OUTPUT = ROOT / "scripts/tradingview/research/pf15_us_8k_price_drift_replay.pine"
PHASES = {"training": 59, "validation": 84, "holdout": 73}
PRICE_KEYS = (
    "entry_raw_open",
    "exit_raw_open",
    "entry_adjusted_open",
    "exit_adjusted_open",
)

PINE_HEADER = r'''//@version=6
// Generated by scripts/export_pf15_us_8k_price_drift_pine.py.
// Closed #46 candidate trades only. Labels use saved Kibot USD prices.
indicator("8-K株価反応｜確定取引の再生", overlay = true, max_labels_count = 500)

var string records = switch syminfo.ticker
'''

PINE_FOOTER = r'''    => ""

var map<string, string> entries = map.new<string, string>()
var map<string, string> exits = map.new<string, string>()
if barstate.isfirst and records != ""
    for record in str.split(records, ";")
        array<string> fields = str.split(record, ",")
        string entryDay = fields.get(0)
        string exitDay = fields.get(1)
        entries.put(entryDay, "Entry " + entryDay + "\nKibot $" + fields.get(2) + "\n完全調整 $" + fields.get(4))
        exits.put(exitDay, "Exit " + exitDay + "\nKibot $" + fields.get(3) + "\n完全調整 $" + fields.get(5))

bool supportedChart = chart.is_standard and timeframe.isdaily and timeframe.multiplier == 1 and syminfo.type == "stock" and syminfo.currency == "USD"
if supportedChart and barstate.isconfirmed
    string day = str.format_time(time, "yyyy-MM-dd", "America/New_York")
    if entries.contains(day)
        label.new(bar_index, low, entries.get(day), yloc = yloc.belowbar, style = label.style_label_up, color = color.teal, textcolor = color.white, size = size.small)
    if exits.contains(day)
        label.new(bar_index, high, exits.get(day), yloc = yloc.abovebar, style = label.style_label_down, color = color.maroon, textcolor = color.white, size = size.small)

var table summary = table.new(position.top_right, 1, 1)
if barstate.islast
    string detail = "米国株の標準1日足で表示"
    if supportedChart
        detail := records == "" ? "内蔵取引なし" : syminfo.ticker + "｜内蔵 " + str.tostring(entries.size()) + " 件"
    table.cell(summary, 0, 0, "2020–2025 確定取引の再生\n" + detail, text_color = color.white, bgcolor = color.new(color.black, 15))
'''


def build_pine() -> str:
    records = defaultdict(list)
    for phase, expected in PHASES.items():
        source = EXPERIMENT / f"{phase}_results.json"
        payload = json.loads(source.read_bytes())
        trades = [trade for trade in payload["windows"] if trade["status"] == "closed"]
        if len(trades) != expected or not payload["gate_passed"]:
            raise ValueError(f"{source.name}: expected {expected} closed trades and a passing gate")
        for trade in trades:
            ticker = trade["entry_ticker"]
            entry = date.fromisoformat(trade["entry_date"])
            exit_day = date.fromisoformat(trade["exit_date"])
            if not ticker.isascii() or not ticker.isalpha() or ticker != trade["exit_ticker"] or entry >= exit_day:
                raise ValueError(f"{source.name}: invalid or cross-symbol trade {trade['accession']}")
            candidate = trade["cases"]["normal"]["candidate"]
            prices = tuple(Decimal(candidate[key]) for key in PRICE_KEYS)
            if any(not price.is_finite() or price <= 0 for price in prices):
                raise ValueError(f"{source.name}: invalid price in {trade['accession']}")
            records[ticker].append((entry, exit_day, *(format(price, "f") for price in prices)))

    lines = []
    for ticker, trades in sorted(records.items()):
        for date_index in (0, 1):
            if len({trade[date_index] for trade in trades}) != len(trades):
                raise ValueError(f"{ticker}: duplicate entry or exit date")
        encoded = ";".join(",".join(map(str, trade)) for trade in sorted(trades))
        lines.append(f'    "{ticker}" => "{encoded}"\n')
    if len(records) != 30:
        raise ValueError("expected 30 trade tickers")
    return PINE_HEADER + "".join(lines) + PINE_FOOTER


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed overlay differs from generated output")
    args = parser.parse_args()
    expected = build_pine()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Replay needs regeneration: {OUTPUT}")
        print(f"Replay matches the source trade records: {OUTPUT}")
    else:
        OUTPUT.write_bytes(expected.encode("utf-8"))


if __name__ == "__main__":
    main()
